-- 1. Tabla de configuración general, enlace externo del APK y Comunidad Telegram
CREATE TABLE IF NOT EXISTS public.app_settings (
    id INT PRIMARY KEY DEFAULT 1,
    app_version TEXT NOT NULL DEFAULT '2.5.6',
    apk_url TEXT NOT NULL DEFAULT 'https://drive.google.com/drive/folders/tu-carpeta-apk',
    apk_provider TEXT NOT NULL DEFAULT 'Google Drive',
    apk_size TEXT NOT NULL DEFAULT '24.8 MB',
    apk_updated_at TEXT NOT NULL DEFAULT 'Noviembre 2026',
    apk_changelog TEXT NOT NULL DEFAULT 'Optimización de caché offline, nuevo escáner OCR de precios con ML Kit y mejoras en Próxima Tasa BCV.',
    telegram_url TEXT NOT NULL DEFAULT 'https://t.me/+A6xwBk-NT_Y1NGRh',
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

INSERT INTO public.app_settings (id) VALUES (1) ON CONFLICT (id) DO NOTHING;

-- 2. Tabla de artículos del Blog (subidos por el Administrador)
CREATE TABLE IF NOT EXISTS public.posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    category TEXT NOT NULL DEFAULT 'Novedades',
    summary TEXT NOT NULL,
    content TEXT NOT NULL,
    read_time TEXT NOT NULL DEFAULT '3 min',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Tabla de Notificaciones del Portal Web
CREATE TABLE IF NOT EXISTS public.notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    message TEXT NOT NULL,
    type TEXT NOT NULL DEFAULT 'info', -- 'rate' | 'update' | 'info'
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Tabla de Comentarios y Sugerencias de Usuarios (con sistema de puntaje 1-5 estrellas por comentario)
CREATE TABLE IF NOT EXISTS public.comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_name TEXT NOT NULL,
    comment_type TEXT NOT NULL DEFAULT 'Sugerencia', -- 'Comentario' | 'Sugerencia' | 'Experiencia'
    content TEXT NOT NULL,
    rating_sum INT NOT NULL DEFAULT 5,
    rating_count INT NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Habilitar Políticas RLS (Row Level Security)
ALTER TABLE public.app_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.posts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.notifications ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.comments ENABLE ROW LEVEL SECURITY;

-- Políticas de lectura y escritura para el cliente web
CREATE POLICY "Lectura publica de configuracion" ON public.app_settings FOR SELECT USING (true);
CREATE POLICY "Actualizacion de configuracion desde admin" ON public.app_settings FOR UPDATE USING (true);
CREATE POLICY "Insercion de configuracion" ON public.app_settings FOR INSERT WITH CHECK (true);

CREATE POLICY "Lectura publica de posts" ON public.posts FOR SELECT USING (true);
CREATE POLICY "Gestion de posts desde admin" ON public.posts FOR ALL USING (true);

CREATE POLICY "Lectura publica de notificaciones" ON public.notifications FOR SELECT USING (true);
CREATE POLICY "Gestion de notificaciones desde admin" ON public.notifications FOR ALL USING (true);

CREATE POLICY "Lectura publica de comentarios" ON public.comments FOR SELECT USING (true);
CREATE POLICY "Publicacion libre de comentarios" ON public.comments FOR INSERT WITH CHECK (true);
CREATE POLICY "Votacion de 5 estrellas en comentarios" ON public.comments FOR UPDATE USING (true);
CREATE POLICY "Moderacion de comentarios desde admin" ON public.comments FOR DELETE USING (true);
